from fastmcp import FastMCP
import psutil
import os
import webbrowser
import urllib.parse
from datetime import datetime, timedelta

# Initialize
mcp = FastMCP("system-tools")

# --- HELPER: GENERATE RICH HTML DASHBOARD ---
def generate_html_dashboard():
    # 1. Gather Data
    cpu = psutil.cpu_percent(interval=1)
    memory = psutil.virtual_memory()
    mem_used = round(memory.used / (1024**3), 2)
    mem_total = round(memory.total / (1024**3), 2)
    
    try:
        disk = psutil.disk_usage('C:\\')
        disk_free = round(disk.free / (1024**3), 2)
        disk_total = round(disk.total / (1024**3), 2)
        disk_pct = disk.percent
    except:
        disk_pct = 0
        disk_free = "N/A"
        disk_total = "N/A"

    boot_time = datetime.fromtimestamp(psutil.boot_time())
    uptime = str(datetime.now() - boot_time).split('.')[0]
    
    # 2. Colors & CSS
    # If CPU > 50, turn bar Orange. If > 80, Red.
    cpu_color = "#2ecc71" if cpu < 50 else "#f1c40f" if cpu < 80 else "#e74c3c"
    ram_color = "#2ecc71" if memory.percent < 70 else "#f1c40f" if memory.percent < 90 else "#e74c3c"
    disk_color = "#2ecc71" if disk_pct < 80 else "#e74c3c"

    html = f"""
    <!DOCTYPE html>
    <html>
    <head>
        <style>
            body {{ font-family: 'Segoe UI', Tahoma, Geneva, Verdana, sans-serif; background-color: #1e1e1e; color: #ffffff; padding: 20px; }}
            .card {{ background-color: #2d2d2d; border-radius: 10px; padding: 20px; max-width: 600px; margin: auto; box-shadow: 0 4px 15px rgba(0,0,0,0.5); }}
            h2 {{ border-bottom: 2px solid #444; padding-bottom: 10px; color: #ffffff; }}
            .metric {{ margin-bottom: 20px; }}
            .label {{ display: flex; justify-content: space-between; font-weight: bold; margin-bottom: 5px; }}
            .bar-bg {{ background-color: #444; height: 10px; border-radius: 5px; overflow: hidden; }}
            .bar-fill {{ height: 100%; border-radius: 5px; transition: width 0.5s ease; }}
            .details {{ font-size: 12px; color: #aaa; margin-top: 4px; }}
            .footer {{ text-align: center; margin-top: 20px; color: #666; font-size: 11px; }}
        </style>
    </head>
    <body>
        <div class="card">
            <h2>🖥️ System Health Protocol</h2>
            <p style="color: #bbb;">📅 {datetime.now().strftime('%Y-%m-%d %H:%M')}</p>
            
            <div class="metric">
                <div class="label"><span>🚀 CPU Load</span> <span>{cpu}%</span></div>
                <div class="bar-bg"><div class="bar-fill" style="width: {cpu}%; background-color: {cpu_color};"></div></div>
                <div class="details">Processor Status: {"Normal" if cpu < 80 else "Heavy Load"}</div>
            </div>

            <div class="metric">
                <div class="label"><span>🧠 RAM Usage</span> <span>{memory.percent}%</span></div>
                <div class="bar-bg"><div class="bar-fill" style="width: {memory.percent}%; background-color: {ram_color};"></div></div>
                <div class="details">{mem_used} GB used of {mem_total} GB</div>
            </div>

            <div class="metric">
                <div class="label"><span>💾 Disk (C:)</span> <span>{disk_pct}% Full</span></div>
                <div class="bar-bg"><div class="bar-fill" style="width: {disk_pct}%; background-color: {disk_color};"></div></div>
                <div class="details">{disk_free} GB Free (Total: {disk_total} GB)</div>
            </div>

            <div class="metric">
                <div class="label"><span>⏱️ Uptime</span> <span style="color: #3498db;">{uptime}</span></div>
            </div>
            
            <div class="footer">Generated by Claude MCP Technician Assistant</div>
        </div>
    </body>
    </html>
    """
    return html

# --- TOOL 1: EXECUTE WORKFLOW (Browser Magic) ---
@mcp.tool()
def open_dashboard_workflow(recipient: str) -> str:
    """
    Generates a graphical HTML dashboard, saves it, and opens it + Gmail.
    """
    # 1. Create the HTML File
    html_content = generate_html_dashboard()
    filename = f"Health_Dashboard_{datetime.now().strftime('%Y-%m-%d')}.html"
    filepath = os.path.join(os.path.expanduser("~"), "Documents", filename)
    
    with open(filepath, "w", encoding="utf-8") as f:
        f.write(html_content)

    # 2. Open the HTML Report in Browser (User copies this)
    webbrowser.open(f"file:///{filepath}")
    
    # 3. Open Gmail Compose Window (User pastes here)
    subject = urllib.parse.quote(f"System Health Report - {datetime.now().strftime('%Y-%m-%d')}")
    gmail_url = f"https://mail.google.com/mail/?view=cm&fs=1&to={recipient}&su={subject}"
    webbrowser.open(gmail_url)

    # 4. Open Calendar (Standard)
    today = datetime.now()
    days_ahead = 7 - today.weekday()
    if days_ahead <= 0: days_ahead += 7
    next_monday = today + timedelta(days=days_ahead)
    start_time = next_monday.replace(hour=10, minute=0, second=0).strftime('%Y%m%dT%H%M00')
    end_time = next_monday.replace(hour=10, minute=30, second=0).strftime('%Y%m%dT%H%M00')
    cal_url = f"https://calendar.google.com/calendar/render?action=TEMPLATE&text=Laptop+Maintenance&dates={start_time}/{end_time}"
    webbrowser.open(cal_url)

    return f"✅ SUCCESS! I opened the graphical report and your email.\n👉 ACTION: Press Ctrl+A -> Ctrl+C on the Report tab, then Ctrl+V into the Gmail tab."

